/**
 * Returns the canonical Practice Blueprint for a given career role slug.
 */
export function getRolePracticeBlueprint(roleSlug: string): RolePracticeBlueprint {
  const normalizedSlug = (roleSlug || 'full-stack-developer').toLowerCase().trim();
  const config = ROLE_BLUEPRINT_CONFIGS[normalizedSlug] || ROLE_BLUEPRINT_CONFIGS['full-stack-developer'];
  const roleId = getRoleUuid(normalizedSlug);

  const categories: PracticeCategory[] = config.categories.map((cat, idx) => ({
    id: cat.id,
    careerRoleSlug: normalizedSlug,
    careerRoleId: roleId,
    title: cat.title,
    shortTitle: cat.shortTitle,
    description: cat.description,
    iconName: cat.iconName,
    environment: cat.environment,
    evaluationType: cat.evaluationType,
    skillNames: cat.skillNames,
    difficultyRange: ['BEGINNER', 'EXPERT'],
    displayOrder: idx + 1,
    isActive: true,
    freeLearningUrl: cat.freeLearningUrl,
    freeLearningProvider: cat.freeLearningProvider
  }));

  return {
    careerRoleId: roleId,
    careerRoleSlug: normalizedSlug,
    careerRoleTitle: config.title,
    tagline: config.tagline,
    subtitle: config.subtitle,
    categories,
    totalChallenges: 0 // populated by catalog
  };
}

/**
 * Returns all 12 supported career role slugs for practice arena verification.
 */
export function getSupportedPracticeRoleSlugs(): string[] {
  return Object.keys(ROLE_BLUEPRINT_CONFIGS);
}
