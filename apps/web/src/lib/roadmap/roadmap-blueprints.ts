/**
 * Safely retrieve career blueprint by slug, falling back to full-stack-developer.
 */
export function getCareerBlueprint(slug: string): CareerBlueprint {
  const normalized = (slug || '').toLowerCase().trim();
  if (CAREER_BLUEPRINTS[normalized]) {
    return CAREER_BLUEPRINTS[normalized];
  }
  return CAREER_BLUEPRINTS['full-stack-developer'];
}
